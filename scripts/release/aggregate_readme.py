#!/usr/bin/env python3
"""Render the README of the `leanprover/hex` aggregate from `released.yml`.

The aggregate publishes no source from this monorepo, so its README used to
be hand-maintained in the released repo and drifted behind every release.
Here the prose lives in a template (`hex-README.md`) and the library table is
generated from the manifest, so a newly released library shows up in the
README on the next sync without anyone remembering to add a row.

`scripts/release/check_released_manifest.py` enforces the other half of the
invariant: every aggregated computational library must carry a `component:`
label, so the table can never silently omit one.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "hex-README.md"
BEGIN = "<!-- LIBRARIES:BEGIN"
END = "<!-- LIBRARIES:END -->"
ANNOUNCE_BEGIN = "<!-- ANNOUNCEMENTS:BEGIN"
ANNOUNCE_END = "<!-- ANNOUNCEMENTS:END -->"
# Rendered in this order, whichever of them a library has.
VENUES = (("blog", "blog post"), ("zulip", "Zulip"), ("linkedin", "LinkedIn"))
NO_LAYER = "n/a"
# Replaces the template's own editor note in the published file: the released
# repo's reader needs to know the file is generated and where to edit it, not
# how the template works.
NOTICE = ("<!-- Generated by scripts/release/sync_released.py from "
          "scripts/release/hex-README.md in https://github.com/kim-em/hex-dev. "
          "Edit it there; changes made here are overwritten. -->\n")


def table_entries(manifest: dict) -> list[dict]:
    """The manifest entries that get a row, in manifest (topological) order.

    A row is one computational library: entries that are part of the
    aggregate, are not the aggregate itself, and are not the `*Mathlib`
    companion of another entry (those appear in the third column instead).
    """
    aggregated = [
        entry for entry in manifest["repos"]
        if not entry.get("pins_only") and entry.get("aggregate", True)
    ]
    libs = {entry["lib"] for entry in aggregated}
    return [
        entry for entry in aggregated
        if not (entry["lib"].endswith("Mathlib")
                and entry["lib"].removesuffix("Mathlib") in libs)
    ]


def mathlib_layer(entry: dict, manifest: dict) -> dict | None:
    """The `*Mathlib` companion entry of a computational entry, if released."""
    companion = entry["lib"] + "Mathlib"
    for other in manifest["repos"]:
        if other.get("lib") == companion:
            return other
    return None


def _link(entry: dict) -> str:
    return f"[{entry['lib']}](https://github.com/{entry['repo']})"


def render_table(manifest: dict) -> str:
    rows = [
        "| Component | Computational | Mathlib layer |",
        "|---|---|---|",
    ]
    for entry in table_entries(manifest):
        component = entry.get("component")
        if not component:
            raise ValueError(
                f"{entry['repo']}: aggregated library needs a `component:` "
                "label for the leanprover/hex README table"
            )
        layer = mathlib_layer(entry, manifest)
        rows.append(
            f"| {component} | {_link(entry)} | "
            f"{_link(layer) if layer else NO_LAYER} |"
        )
    return "\n".join(rows)


def render_announcements(manifest: dict) -> str:
    """Where each library was announced, one line per library that has any.

    Kept out of the table: only a couple of libraries are ever announced, and a
    column would be empty for almost every row.
    """
    lines = []
    for entry in table_entries(manifest):
        announcements = entry.get("announcements") or {}
        links = [f"[{label}]({announcements[key]})"
                 for key, label in VENUES if announcements.get(key)]
        if links:
            lines.append(f"- {entry['component']} ({_link(entry)}): "
                         + ", ".join(links))
    return "\n".join(lines)


def _splice(text: str, begin: str, end: str, body: str, what: str) -> str:
    """Replace the region between two markers, keeping the marker lines."""
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < 0 or stop < start:
        raise ValueError(f"template is missing its {what} markers")
    return text[:text.index("\n", start) + 1] + body + "\n" + text[stop:]


def render(manifest: dict, template: Path = TEMPLATE) -> str:
    """The full README text for the aggregate."""
    text = template.read_text(encoding="utf-8")
    if text.startswith("<!--"):
        text = NOTICE + text[text.index("-->\n") + len("-->\n"):]
    try:
        text = _splice(text, BEGIN, END, render_table(manifest), "LIBRARIES")
        return _splice(text, ANNOUNCE_BEGIN, ANNOUNCE_END,
                       render_announcements(manifest), "ANNOUNCEMENTS")
    except ValueError as exc:
        raise ValueError(f"{template}: {exc}") from None


if __name__ == "__main__":
    import yaml

    document = yaml.safe_load((HERE / "released.yml").read_text(encoding="utf-8"))
    print(render(document), end="")
