#!/usr/bin/env python3
"""Deterministic offline Conway source generation. Requires SymPy 1.14.0.

Inputs are scope.json and candidates.json; coefficient import is a separate
network operation. Polynomial arithmetic and factor searches run only here.
Every emitted result is checked by Lean, including factor primality.
"""
