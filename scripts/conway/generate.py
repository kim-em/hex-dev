def module(imports):
    return (
        HEADER
        + "".join(f"public import {i}\n" for i in imports)
        + "\npublic section\n\n/-! Generated by scripts/conway/generate.py from the committed scope and source data. -/\n\nset_option maxRecDepth 1000000\nset_option maxHeartbeats 80000000\n\nnamespace Hex\nnamespace Conway\n\n"
    )


def trim(a):
    while a and a[-1] == 0:
        a.pop()
    return a


def add(a, b, p):
    return trim(
        [
            ((a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0)) % p
            for i in range(max(len(a), len(b)))
        ]
    )


def neg(a, p):
    return [(-x) % p for x in a]


def mul(a, b, p):
    r = [0] * max(0, len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            r[i + j] = (r[i + j] + x * y) % p
    return trim(r)


def div(a, b, p):
    a = a[:]
    q = [0] * max(0, len(a) - len(b) + 1)
    while a and len(a) >= len(b):
        k = len(a) - len(b)
        c = a[-1] * pow(b[-1], -1, p) % p
        q[k] = c
        a = add(a, [0] * k + neg([(c * x) % p for x in b], p), p)
    return trim(q), a


def power(a, k, f, p):
    r = [1]
    a = div(a, f, p)[1]
    while k:
        if k % 2:
            r = div(mul(r, a, p), f, p)[1]
        a = div(mul(a, a, p), f, p)[1]
        k //= 2
    return r


def bezout(a, b, p):
    s, t, u, v = [1], [], [], [1]
    while b:
        q, r = div(a, b, p)
        a, b = b, r
        s, u = u, add(s, neg(mul(q, u, p), p), p)
        t, v = v, add(t, neg(mul(q, v, p), p), p)
    assert len(a) == 1
    c = pow(a[0], -1, p)
    return [(x * c) % p for x in s], [(x * c) % p for x in t]


@lru_cache(None)
def factors(n):
    return sorted((int(q), int(e)) for q, e in sympy.factorint(n).items())


def poly(p, a):
    if not a:
        return f"FpPoly.ofCoeffs (#[] : Array (ZMod64 {p}))"
    return (
        f"FpPoly.ofCoeffs #[({a[0]} : ZMod64 {p})"
        + "".join(f", {x}" for x in a[1:])
        + "]"
    )


def name(p, n):
    return f"luebeckConwayPolynomial_{p}_{n}"


def cert(p, n, c):
    chain = [div([0, 1], c, p)[1]]
    for _ in range(n):
        chain.append(power(chain[-1], p, c, p))
    assert chain[-1] == chain[0], (p, n)
    ds = sorted(n // q for q, _ in factors(n)) if n > 1 else []
    witnesses = [bezout(c, div(add(chain[d], [0, p - 1], p), c, p)[1], p) for d in ds]
    nm = name(p, n)
    return f"""/-- Rabin certificate for C({p}, {n}). -/
private def cert_{p}_{n} : Berlekamp.IrreducibilityCertificate where
  p := {p}
  n := {n}
  powChain := #[{', '.join(poly(p,a) for a in chain)}]
  bezout := #[{', '.join('{ left := '+poly(p,a)+', right := '+poly(p,b)+' }' for a,b in witnesses)}]

/-- Irreducibility of the imported C({p}, {n}). -/
@[grind .] theorem {nm}_irreducible : FpPoly.Irreducible {nm} :=
  Berlekamp.rabinTest_imp_irreducible {nm} {nm}_monic
    (Berlekamp.checkIrreducibilityCertificateLinearIncremental_rabinTest
      {nm} {nm}_monic cert_{p}_{n}
      (by rw [← checkRabin_eq]; decide +kernel))

"""


def table(entries):
    out = module(
        [
            "HexBerlekamp.RabinSoundness",
            "HexGFqRing.PolynomialQuotient",
            "HexArith.Nat.Prime",
        ]
    )
    words = {2: "two", 3: "three", 5: "five", 7: "seven", 11: "eleven", 13: "thirteen"}
    for p in sorted({p for p, n, c in entries}):
        if p != 2:
            out += f"/-- Word bounds for characteristic {p}. -/\ninstance bounds{p} : ZMod64.Bounds {p} := ⟨by decide, by decide⟩\n"
        pn = "prime_" + words.get(p, str(p))
        out += f"/-- Primality of characteristic {p}. -/\ntheorem {pn} : Hex.Nat.Prime {p} :=\n  Hex.Nat.prime_of_bounded {p} {isqrt(p)} (by decide) (by decide) (by decide)\n"
        out += f"/-- Prime modulus for characteristic {p}. -/\ninstance instPrimeModulus{p} : ZMod64.PrimeModulus {p} := ZMod64.primeModulusOfPrime {pn}\n\n"
    out += """/-- Imported coefficients in ascending degree order. -/
@[expose] def luebeckConwayCoeffs? : Nat → Nat → Option (List Nat)
"""
    for p in sorted({p for p, n, c in entries}):
        out += f"  | {p}, n => match n with\n"
        out += "".join(f"    | {n} => some {c}\n" for q, n, c in entries if p == q)
        out += "    | _ => none\n"
    out += "  | _, _ => none\n\n"
    out += """/-- Construct a polynomial from ascending coefficient representatives. -/
@[expose] def luebeckConwayPolynomialOfCoeffs
    (p : Nat) [ZMod64.Bounds p] (coeffs : List Nat) : FpPoly p :=
  FpPoly.ofCoeffs (coeffs.toArray.map (fun n => ZMod64.ofNat p n))

/-- Lookup an imported, verified polynomial. -/
@[expose] def luebeckConwayPolynomial? (p n : Nat) [ZMod64.Bounds p] : Option (FpPoly p) :=
  (luebeckConwayCoeffs? p n).map (luebeckConwayPolynomialOfCoeffs p)

/-- Exact verified keys, in characteristic and degree order. -/
@[expose] def supportedPairs : List (Nat × Nat) :=
  """ + str([(p, n) for p, n, c in entries]) + "\n\n"
    for p, n, c in entries:
        nm = name(p, n)
        out += f"""/-- Imported C({p}, {n}), with ascending coefficients. -/
@[expose] def {nm} : FpPoly {p} :=
  {{ coeffs := #[({c[0]} : ZMod64 {p}){''.join(f', {x}' for x in c[1:])}]
    normalized := by right; decide }}

/-- Monicity of C({p}, {n}). -/
@[simp, grind .] theorem {nm}_monic : DensePoly.Monic {nm} := by rfl

/-- Positive degree of C({p}, {n}). -/
@[simp, grind .] theorem {nm}_degree_pos : 0 < FpPoly.degree {nm} := by decide

/-- Lookup identifies the imported C({p}, {n}). -/
@[simp, grind =] theorem luebeckConwayPolynomial?_hit_{p}_{n} :
    luebeckConwayPolynomial? {p} {n} = some {nm} := by
  show some (luebeckConwayPolynomialOfCoeffs {p} {c}) = some {nm}
  congr 1
  apply DensePoly.ext_coeff
  intro k
  rw [show DensePoly.coeff (luebeckConwayPolynomialOfCoeffs {p} {c}) k =
        ({c}.toArray.map (fun m => ZMod64.ofNat {p} m)).getD k
          (Zero.zero : ZMod64 {p}) from DensePoly.coeff_ofCoeffs _ k]
  simp [List.toArray, Array.map, DensePoly.coeff, {nm}]
  match k with
{chr(10).join(f'  | {i} => rfl' for i in range(len(c)))}
  | _ + {len(c)} => rfl

"""
    return out + END


def api(entries, template):
    out = module(["HexConway.Certificates"])
    for p, n, c in entries:
        for prop, ty in [
            ("irreducible", "FpPoly.Irreducible"),
            ("monic", "DensePoly.Monic"),
        ]:
            out += f"""private theorem ofCoeffs_{p}_{n}_{prop} :
    {ty} (luebeckConwayPolynomialOfCoeffs {p} {c}) := by
  have heq := Option.some.inj luebeckConwayPolynomial?_hit_{p}_{n}
  change luebeckConwayPolynomialOfCoeffs {p} {c} = {name(p,n)} at heq
  rw [heq]
  exact {name(p,n)}_{prop}

"""
    for prop, ty in [
        ("irreducible", "FpPoly.Irreducible"),
        ("monic", "DensePoly.Monic"),
    ]:
        out += f"""/-- Every successful lookup carries {prop} certification. -/
@[grind →] theorem luebeckConwayPolynomial?_{prop}
    {{p n : Nat}} [ZMod64.Bounds p] {{f : FpPoly p}}
    (h : luebeckConwayPolynomial? p n = some f) : {ty} f := by
  unfold luebeckConwayPolynomial? at h
  rw [Option.map_eq_some_iff] at h
  obtain ⟨coeffs, hcoeffs, hf⟩ := h
  subst hf
  unfold luebeckConwayCoeffs? at hcoeffs
  split at hcoeffs
"""
        for p in sorted({p for p, n, c in entries}):
            out += "  · split at hcoeffs\n"
            out += "".join(
                f"    · cases hcoeffs; exact ofCoeffs_{p}_{n}_{prop}\n"
                for q, n, c in entries
                if p == q
            )
            out += "    · cases hcoeffs\n"
        out += "  · cases hcoeffs\n\n"
    out += """/-- A lookup witness for a committed polynomial. -/
structure SupportedEntry (p n : Nat) [ZMod64.Bounds p] where
  /-- The selected polynomial. -/
  poly : FpPoly p
  /-- Its characteristic is prime. -/
  prime : Hex.Nat.Prime p
  /-- The table selects this polynomial. -/
  isSupported : luebeckConwayPolynomial? p n = some poly

"""
    words = {2: "two", 3: "three", 5: "five", 7: "seven", 11: "eleven", 13: "thirteen"}
    for p, n, c in entries:
        out += f"""/-- The verified table supports C({p}, {n}). -/
@[expose] def supportedEntry_{p}_{n} : SupportedEntry {p} {n} :=
  ⟨{name(p,n)}, prime_{words.get(p,str(p))}, luebeckConwayPolynomial?_hit_{p}_{n}⟩

"""
    return out + template


def primitive(entries):
    out = ""
    for p, n, c in entries:
        fs = factors(p**n - 1) if p**n > 2 else []
        qs = [q for q, e in fs]
        es = [e for q, e in fs]
        out += f"""/-- C({p}, {n}) has a generator of order {p**n-1}. -/
theorem primitive_{p}_{n} :
    Primitive {p} {n} supportedEntry_{p}_{n} {qs} {es} where
  primes := by
    intro q hq
"""
        for q in qs:
            out += f"""    rcases List.mem_cons.mp hq with rfl | hq
    · exact factorPrime_{q}
"""
        out += "    exact absurd hq (by simp)\n  check := by decide +kernel\n\n"
    return out


def replace_generated(path, body):
    s = path.read_text()
    a, b = s.split("-- BEGIN GENERATED\n", 1)
    _, c = b.split("-- END GENERATED", 1)
    path.write_text(a + "-- BEGIN GENERATED\n" + body + "-- END GENERATED" + c)


def shards(folder, blocks, imports, predecessors=None):
    """Four serial import chains bound simultaneous generated proof modules.

    Each shard also stays below the repository's source-file line budget.
    """
    directory = ROOT / "HexConway" / folder
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("*.lean"):
        old.unlink()

    def weight(block):
        keys = re.findall(r"C\((\d+), (\d+)\)", block)
        if keys:
            p, n = map(int, keys[-1])
            return max(1, n**3 * p.bit_length() * len(factors(p**n - 1)))
        # Transport blocks only wrap proofs; balance them by source line count.
        return len(block.splitlines())

    lanes, costs = [[], [], [], []], [0, 0, 0, 0]
    for block in sorted(blocks, key=weight, reverse=True):
        lane = min(range(4), key=lambda i: costs[i])
        lanes[lane].append(block)
        costs[lane] += weight(block)
    names = []
    for lane in range(4):
        chunks, current, lines = [], [], 0
        for block in lanes[lane]:
            size = len(block.splitlines())
            if current and (lines + size > 1200 or len(current) >= 24):
                chunks.append(current)
                current, lines = [], 0
            current.append(block)
            lines += size
        if current:
            chunks.append(current)
        previous = None
        for i, chunk in enumerate(chunks):
            name_ = f"HexConway.{folder}.S{lane}_{i}"
            dependencies = imports + (
                [previous] if previous else (predecessors[lane] if predecessors else [])
            )
            (directory / f"S{lane}_{i}.lean").write_text(
                module(dependencies) + "".join(chunk) + END
            )
            names.append(name_)
            previous = name_
    return names


def generated_imports(path, folder, names):
    source = path.read_text()
    source = re.sub(
        rf"^public import HexConway\.{folder}\..*\n", "", source, flags=re.M
    )
    source = source.replace(
        "public section",
        "".join(f"public import {n}\n" for n in names) + "\npublic section",
        1,
    )
    if not source.startswith("/-"):
        source = HEADER.split("module")[0] + source
    path.write_text(re.sub(r"\n{3,}", "\n\n", source))


def factor_proofs(entries):
    """Share every Pocklington child proof; prime dependencies are smaller."""
    needed = {q for p, n, c in entries for q, e in factors(p**n - 1)}
    pending = list(needed)
    while pending:
        q = pending.pop()
        if q >= 100000:
            for r, e in factors(q - 1):
                if r not in needed:
                    needed.add(r)
                    pending.append(r)
    blocks = []
    for q in sorted(needed):
        body = f"/-- Primality of a multiplicative-order factor or a Pocklington child. -/\ntheorem factorPrime_{q} : Hex.Nat.Prime {q} := by\n"
        if q < 100000:
            body += f"  exact Hex.Nat.prime_of_bounded {q} {isqrt(q)} (by decide) (by decide) (by decide)\n\n"
        else:
            fs = factors(q - 1)
            witnesses = []
            for r, e in fs:
                a = 2
                while pow(a, q - 1, q) != 1 or gcd(pow(a, (q - 1) // r, q) - 1, q) != 1:
                    a += 1
                witnesses.append(f"({a}, {e-1}, .small {r})")
            body += (
                "  apply Hex.Nat.prime_of_pocklington (factors := ["
                + ", ".join(witnesses)
                + "])\n"
            )
            body += "  · decide +kernel\n  · intro x hx\n    simp only [List.mem_cons, List.mem_nil_iff, or_false] at hx\n"
            body += "    rcases hx with " + " | ".join("rfl" for _ in fs) + "\n"
            body += "".join(f"    · exact factorPrime_{r}\n" for r, e in fs) + "\n"
        blocks.append(body)
    directory = ROOT / "HexConway/FactorProofs"
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("*.lean"):
        old.unlink()
    names = []
    for i in range(0, len(blocks), 24):
        name_ = f"HexConway.FactorProofs.S0_{i//24}"
        imports = ["HexPrimality.Cert"] + names[-1:]
        (directory / f"S0_{i//24}.lean").write_text(
            module(imports) + "".join(blocks[i : i + 24]) + END
        )
        names.append(name_)
    return names


def companions(entries):
    """Instance-selected fields and Mathlib order specializations share the scope."""
    for library, folder, namespace, core in [
        ("HexGFq", "Entries", "Hex.GFq", "HexGFq.Entry"),
        (
            "HexGFqMathlib",
            "GeneratorOrder",
            "HexGFqMathlib",
            "HexGFqMathlib.PrimitivityCore",
        ),
    ]:
        directory = ROOT / library / folder
        directory.mkdir(parents=True, exist_ok=True)
        for old in directory.glob("*.lean"):
            old.unlink()
        names = []
        for i in range(0, len(entries), 128):
            name_ = f"{library}.{folder}.S{i//128}"
            names.append(name_)
            body = (
                HEADER
                + f"public import {core}\n\npublic section\n\nnamespace {namespace}\n\n"
            )
            for p, n, c in entries[i : i + 128]:
                if library == "HexGFq":
                    body += f"/-- Instance-selected field for C({p}, {n}). -/\ninstance committedEntry_{p}_{n} : CommittedEntry {p} {n} where\n  entry := Hex.Conway.supportedEntry_{p}_{n}\n\n"
                else:
                    body += f"/-- The Conway generator of GF({p}^{n}) has order {p**n-1}. -/\ntheorem orderOf_gen_{p}_{n} :\n    orderOf (Hex.GFq.ofPoly Hex.Conway.supportedEntry_{p}_{n} Hex.FpPoly.X) = {p} ^ {n} - 1 :=\n  orderOf_gen_of_primitive _ Hex.Conway.primitive_{p}_{n}\n\n"
            (directory / f"S{i//128}.lean").write_text(body + f"end {namespace}\n")
        target = "Entries" if library == "HexGFq" else "Primitivity"
        (ROOT / library / f"{target}.lean").write_text(
            HEADER
            + "".join(f"public import {n}\n" for n in names)
            + "\npublic section\n"
        )


def embeddings(entries):
    """Specialize the canonical embedding at every supported divisor pair."""
    directory = ROOT / "HexGFqMathlib/Embeddings"
    directory.mkdir(parents=True, exist_ok=True)
    for old in directory.glob("*.lean"):
        old.unlink()
    pairs = [(p, m, n) for p, n, _ in entries for m in range(1, n) if n % m == 0]
    names = []
    for i in range(0, len(pairs), 128):
        names.append(f"HexGFqMathlib.Embeddings.S{i//128}")
        body = (
            HEADER
            + "public import HexGFqMathlib.Subfield\n\npublic section\n\nnamespace HexGFqMathlib.Conway\n\n"
        )
        for p, m, n in pairs[i : i + 128]:
            body += f"/-- The canonical embedding of GF({p}^{m}) into GF({p}^{n}). -/\nnoncomputable def embed_{p}_{m}_{n} :\n    Hex.GFq {p} {m} Hex.Conway.supportedEntry_{p}_{m} →+*\n      Hex.GFq {p} {n} Hex.Conway.supportedEntry_{p}_{n} :=\n  conwayEmbed {p} {m} {n} _ _ Hex.Conway.compat_{p}_{m}_{n}\n\n"
        (directory / f"S{i//128}.lean").write_text(body + "end HexGFqMathlib.Conway\n")
    (ROOT / "HexGFqMathlib/Embeddings.lean").write_text(
        HEADER + "".join(f"public import {n}\n" for n in names) + "\npublic section\n"
    )


def main():
    global ROOT
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scope", type=Path, default=HERE / "scope.json")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    original_root = ROOT
    data = json.loads((HERE / "candidates.json").read_text())
    rows = {(e["p"], e["n"]): e["coeffs"] for e in data["entries"]}
    if data.get("coefficient_order") != "ascending":
        raise ValueError("Expected ascending source coefficients")
    if len(rows) != len(data["entries"]):
        raise ValueError("Duplicate source keys")
    shared = json.loads(
        (original_root / "scripts/oracle/luebeck_conway_cache.json").read_text()
    )["entries"]
    for row in shared:
        key = (row["p"], row["n"])
        if key in rows and row["coeffs"] != rows[key]:
            raise ValueError(f"Shared factorization corpus cache differs at {key}")
    scope = sorted(tuple(k) for k in json.loads(args.scope.read_text()))
    if len(scope) != len(set(scope)):
        raise ValueError("Duplicate scope keys")
    baseline = {
        tuple(k) for k in json.loads((HERE / "baseline-scope.json").read_text())
    }
    if not baseline <= set(scope):
        raise ValueError("The verified baseline must be preserved")
    for p, n in scope:
        if (
            not isinstance(p, int)
            or not isinstance(n, int)
            or not 1 < p < 2**31
            or n < 1
        ):
            raise ValueError(f"Invalid scope key: {(p, n)}")
        if (p, n) not in rows:
            raise ValueError(f"Unavailable source entry: {(p, n)}")
        if not all((p, d) in scope for d in range(1, n + 1) if n % d == 0):
            raise ValueError(f"Missing degree divisor of {(p, n)}")
        if not (
            len(rows[p, n]) == n + 1
            and rows[p, n][-1] == 1
            and all(isinstance(c, int) and 0 <= c < p for c in rows[p, n])
        ):
            raise ValueError(f"Invalid source coefficients: {(p, n)}")
    entries = [(p, n, rows[p, n]) for p, n in scope]
    temp = tempfile.TemporaryDirectory() if args.check else None
    if temp:
        ROOT = Path(temp.name)
        for part in ["HexConway", "HexGFq", "HexGFqMathlib"]:
            (ROOT / part).mkdir()
        for part in ["HexConway/Primitivity.lean", "HexConway/Compatibility.lean"]:
            shutil.copyfile(original_root / part, ROOT / part)
    full_table = table(entries)
    literal_start = full_table.index("/-- Imported C(")
    coeff_start = full_table.index("/-- Imported coefficients")
    (ROOT / "HexConway/Bounds.lean").write_text(full_table[:coeff_start] + END)
    (ROOT / "HexConway/Coefficients.lean").write_text(
        module(["HexConway.Bounds"]) + full_table[coeff_start:literal_start] + END
    )
    literals = re.split(r"(?=/-- Imported C\()", full_table[literal_start : -len(END)])
    names = shards(
        "Entries", [b for b in literals if b.strip()], ["HexConway.Coefficients"]
    )
    (ROOT / "HexConway/Table.lean").write_text(module(names) + END)
    names = shards(
        "Rabin", [cert(*e) for e in entries], ["HexConway.Table", "HexConway.Power"]
    )
    (ROOT / "HexConway/Certificates.lean").write_text(module(names) + END)
    full_api = api(entries, (HERE / "ApiTail.lean.in").read_text())
    start = full_api.index("private theorem")
    lookup_start = full_api.index("/-- Every successful lookup")
    struct_start = full_api.index("/-- A lookup witness")
    supported_start = full_api.index("/-- The verified table supports")
    tail_start = full_api.index("/-- Recover the committed Conway modulus")
    transports = re.split(r"(?=private theorem)", full_api[start:lookup_start])
    names = shards(
        "Transport",
        [b.replace("private theorem", "theorem") for b in transports if b.strip()],
        ["HexConway.Certificates"],
    )
    lookups = re.split(
        r"(?=/-- Every successful lookup)", full_api[lookup_start:struct_start]
    )
    lookups = [b for b in lookups if b.strip()]
    for kind, body in zip(["Irreducible", "Monic"], lookups, strict=True):
        (ROOT / f"HexConway/{kind}.lean").write_text(module(names) + body + END)
    (ROOT / "HexConway/ApiCore.lean").write_text(
        module(["HexConway.Irreducible", "HexConway.Monic"])
        + full_api[struct_start:supported_start]
        + full_api[tail_start:]
    )
    supported = re.split(
        r"(?=/-- The verified table supports)", full_api[supported_start:tail_start]
    )
    names = shards(
        "Supported", [b for b in supported if b.strip()], ["HexConway.ApiCore"]
    )
    (ROOT / "HexConway/Api.lean").write_text(
        module(["HexConway.ApiCore", *names]) + END
    )
    names = factor_proofs(entries)
    (ROOT / "HexConway/PrimeFactors.lean").write_text(module(names) + END)
    names = shards(
        "PrimitiveProofs",
        [primitive([e]) for e in entries],
        ["HexConway.PrimitivityCore", "HexConway.PrimeFactors"],
    )
    replace_generated(ROOT / "HexConway/Primitivity.lean", "")
    generated_imports(ROOT / "HexConway/Primitivity.lean", "PrimitiveProofs", names)
    primitive_ends = [[n for n in names if f".S{i}_" in n][-1:] for i in range(4)]
    compat = ""
    for p, n, c in entries:
        for m in range(1, n):
            if n % m == 0:
                compat += f"/-- Compatibility of C({p}, {m}) with C({p}, {n}). -/\ntheorem compat_{p}_{m}_{n} :\n    Compatible {p} {m} {n} supportedEntry_{p}_{m} supportedEntry_{p}_{n} := by decide +kernel\n\n"
    blocks = re.split(r"(?=/-- Compatibility of)", compat)
    names = shards(
        "CompatibilityProofs",
        [b for b in blocks if b.strip()],
        ["HexConway.CompatibilityCore"],
        predecessors=primitive_ends,
    )
    replace_generated(ROOT / "HexConway/Compatibility.lean", "")
    generated_imports(
        ROOT / "HexConway/Compatibility.lean", "CompatibilityProofs", names
    )
    companions(entries)
    embeddings(entries)
    runtime = (HERE / "Replay.lean.in").read_text().rstrip() + "\n\n"
    for i, (p, n, c) in enumerate(entries):
        if i % 24 == 0:
            runtime += f"\nprivate def run{i//24} : IO Unit := do\n"
        fs = factors(p**n - 1) if p**n > 2 else []
        qs = [q for q, e in fs]
        es = [e for q, e in fs]
        divisors = ", ".join(f"({m}, {name(p,m)})" for m in range(1, n) if n % m == 0)
        runtime += f"  measureEntry {p} {n} ⟨{name(p,n)}, {name(p,n)}_monic⟩ {qs} {es} [{divisors}]\n"
    runtime += "\ndef main : IO Unit := do\n" + "".join(
        f"  run{i}\n" for i in range((len(entries) + 23) // 24)
    )
    (ROOT / "bench/HexConway").mkdir(parents=True, exist_ok=True)
    (ROOT / "bench/HexConway/Replay.lean").write_text(runtime)
    if temp:
        for folder in [
            "Entries",
            "Rabin",
            "Transport",
            "Supported",
            "FactorProofs",
            "PrimitiveProofs",
            "CompatibilityProofs",
        ]:
            expected_names = {
                p.name for p in (ROOT / "HexConway" / folder).glob("*.lean")
            }
            actual_names = {
                p.name for p in (original_root / "HexConway" / folder).glob("*.lean")
            }
            if actual_names != expected_names:
                raise SystemExit(f"Generated file set differs: HexConway/{folder}")
        for folder in [
            "HexGFq/Entries",
            "HexGFqMathlib/GeneratorOrder",
            "HexGFqMathlib/Embeddings",
        ]:
            if {p.name for p in (ROOT / folder).glob("*.lean")} != {
                p.name for p in (original_root / folder).glob("*.lean")
            }:
                raise SystemExit(f"Generated file set differs: {folder}")
        for path in ROOT.rglob("*.lean"):
            expected = original_root / path.relative_to(ROOT)
            if not expected.exists() or expected.read_bytes() != path.read_bytes():
                raise SystemExit(
                    f"Generated output differs: {expected.relative_to(original_root)}"
                )
        temp.cleanup()
    print(
        f'Generated {len(entries)} entries and {compat.count("theorem compat_")} compatibility proofs'
    )


