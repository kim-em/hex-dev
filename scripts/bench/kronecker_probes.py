OPTIONS = "set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n"


def join(op, values, unit):
    values = list(values)
    if not values:
        return ["int", unit]
    if len(values) == 1:
        return values[0]
    middle = len(values) // 2
    return [op, join(op, values[:middle], unit), join(op, values[middle:], unit)]


def polynomial_ast(poly, xs):
    if not xs:
        return ["int", int(poly)]
    terms = []
    for exponents, coefficient in sp.Poly(poly, *xs, domain=sp.ZZ).terms():
        if not coefficient:
            continue
        factors = [] if coefficient == 1 else [["int", int(coefficient)]]
        factors += [["atom", i] if d == 1 else ["pow", ["atom", i], d]
                    for i, d in enumerate(exponents) if d]
        terms.append(join("mul", factors, 1))
    return join("add", terms, 0)


def lean(e):
    op, *args = e
    if op == "int":
        return str(args[0]) if args[0] >= 0 else f"({args[0]})"
    if op == "atom":
        return f"x{args[0]}"
    if op == "pow":
        return f"({lean(args[0])} ^ {args[1]})"
    if op == "neg":
        return f"(-{lean(args[0])})"
    symbol = {"add": "+", "sub": "-", "mul": "*"}[op]
    return f"({lean(args[0])} {symbol} {lean(args[1])})"


def quote(e):
    op, *args = e
    if op in ("int", "atom"):
        value = f"({args[0]})" if args[0] < 0 else str(args[0])
        return f"(.{op} {value})"
    if op == "pow":
        return f"(.pow {quote(args[0])} {args[1]})"
    return f"(.{op} " + " ".join(quote(a) for a in args) + ")"


def determinant(n, k, degree):
    rng = random.Random(10270 + 100*n + 10*k + degree)
    xs = sp.symbols(f"x0:{k}")
    entries = [[sum(rng.randint(-3, 3)*x**degree for x in xs) + rng.randint(-3, 3)
                for _ in range(n)] for _ in range(n)]
    trees = [[polynomial_ast(p, xs) for p in row] for row in entries]
    summands = []
    for perm in itertools.permutations(range(n)):
        sign = (-1)**sum(perm[i] > perm[j] for i in range(n) for j in range(i+1, n))
        summands.append(join("mul", [["int", sign]] + [trees[i][perm[i]] for i in range(n)], 1))
    lhs = join("add", summands, 0)
    rhs = polynomial_ast(sp.Matrix(entries).det(method="domain-ge"), xs)
    assert sp.expand(expr(lhs, xs) - expr(rhs, xs)) == 0
    return lhs, rhs


def independent(n):
    terms = []
    for perm in itertools.permutations(range(n)):
        sign = (-1)**sum(perm[i] > perm[j] for i in range(n) for j in range(i+1, n))
        terms.append(join("mul", [["int", sign]] + [["atom", i*n+perm[i]] for i in range(n)], 1))
    return join("add", terms, 0), join("add", reversed(terms), 0)


def write(name, body):
    (DEST / f"{name}.lean").write_text(HEADER + body)


def make_case(stem, family, k, lhs, rhs, **metadata):
    wire = dict(k=k, op="expr", budget=[65536, 16777216], lhs=lhs, rhs=rhs)
    size = preflight(wire)
    accepted = size["digits"] <= 65536 and size["packedBits"] <= 16777216
    ns = "KroneckerProbe." + stem
    params = " ".join(f"x{i}" for i in range(k))
    write(stem + "Construction", f"module\npublic import HexKroneckerMathlib\n\n" + OPTIONS + f"public section\nnamespace {ns}\n"
          f"def lhs ({params} : Int) : Int := {lean(lhs)}\n"
          f"def rhs ({params} : Int) : Int := {lean(rhs)}\n"
          f"def leftTree : Hex.Kronecker.Expr := {quote(lhs)}\n"
          f"def rightTree : Hex.Kronecker.Expr := {quote(rhs)}\nend {ns}\n")
    imports = f"import {PREFIX}.{stem}Construction\n\n" + OPTIONS + f"open {ns}\n"
    if accepted:
        for arm, tactic in [("Kronecker", "kronecker"), ("Ring", "ring"), ("Grobner", "grobner")]:
            write(stem + arm, imports + f"\nnamespace {ns}.{arm}\n"
                  f"theorem result ({params} : Int) : lhs {params} = rhs {params} := by\n"
                  f"  unfold lhs rhs\n  {tactic}\n#print axioms result\nend {ns}.{arm}\n")
            write(stem + arm + "Baseline", imports)
    else:
        if family == "dense-box-declines":
            digits = "at least 65537" if size["digits"] > 65536 else str(size["digits"])
            bits = "at least 16777217" if size["packedBits"] > 16777216 else str(size["packedBits"])
            message = (f"kronecker declined: dense box requires {digits} digits and {bits} packed bits "
                       f"(limits 65536 digits, 16777216 bits); per-atom degree bounds {size['degrees']}")
            body = f"/-- error: {message} -/\n#guard_msgs in\n"
            body += f"example ({params} : Int) : lhs {params} = rhs {params} := by\n  unfold lhs rhs\n  kronecker\n"
        else:
            body = f"#guard match Hex.Kronecker.sizeExprEq {{}} {k} leftTree rightTree with\n"
            body += "  | .ok s => !s.accepts {}\n  | .error _ => false\n"
        write(stem + "Decline", imports + "\n" + body)
        write(stem + "DeclineBaseline", imports)
    return dict(stem=stem, family=family, atoms=k, accepted=accepted, size=size,
                ceiling_seconds=60 if family == "determinant-identities" else 30,
                cleanup_timeout_seconds=180, **metadata)


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    cases = []
    for k in [1, 2, 3, 4, 6, 8]:
        xs = sp.symbols(f"x0:{k}")
        for d in [2, 4, 8, 16]:
            lhs = ["pow", join("add", [["atom", i] for i in range(k)], 0), d]
            size = preflight(dict(k=k, op="expr", budget=[65536, 16777216], lhs=lhs, rhs=lhs))
            # A declined grid point never requests a sparse expansion either.
            rhs = polynomial_ast(sum(xs)**d, xs) if size["digits"] <= 65536 and size["packedBits"] <= 16777216 else lhs
            cases.append(make_case(f"GridK{k}D{d}", "reflected-identities", k, lhs, rhs, degree=d))
    for n, k, d in [(3, 2, 1), (4, 3, 1), (3, 3, 2), (4, 2, 2), (5, 3, 1)]:
        lhs, rhs = determinant(n, k, d)
        cases.append(make_case(f"DetN{n}K{k}D{d}", "determinant-identities", k, lhs, rhs, n=n, degree=d))
    for n in [5]:
        lhs, rhs = independent(n)
        cases.append(make_case(f"IndependentN{n}", "dense-box-declines", n*n, lhs, rhs, n=n, degree=1))
    profiles = ["GridK3D8", "DetN4K3D1", "IndependentN5"]
    for stem in profiles:
        c = next(c for c in cases if c["stem"] == stem)
        body = f"import {PREFIX}.{stem}Construction\n\n" + OPTIONS
        body += "set_option profiler true\nset_option profiler.threshold 0\n"
        body += f"open KroneckerProbe.{stem}\n"
        if c["accepted"]:
            body += f"theorem kernelResult : Hex.Kronecker.checkExprEq {{}} {c['atoms']} leftTree rightTree = true := by\n  decide +kernel\n#print axioms kernelResult\n"
        else:
            body += f"#guard match Hex.Kronecker.sizeExprEq {{}} {c['atoms']} leftTree rightTree with\n  | .ok s => !s.accepts {{}}\n  | .error _ => false\n"
        write(stem + "Profile", body)
    manifest = dict(schema="hex-kronecker-probes-v1", trials=6, order="adjacent AB/BA with adjacent import baselines",
                    cases=cases, profiles=profiles)
    (ROOT / "scripts/bench/kronecker_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
